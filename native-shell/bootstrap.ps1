[CmdletBinding()]
param(
    [string]$Workspace = "D:\SkAiBuild",
    [string]$ChromiumGostRef = "156.0.8078.88",
    [switch]$InitializeChromiumCheckout
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

function Invoke-NativeCommand {
    param(
        [Parameter(Mandatory)][string]$FilePath,
        [Parameter(Mandatory)][string[]]$Arguments,
        [Parameter(Mandatory)][string]$WorkingDirectory
    )
    Push-Location $WorkingDirectory
    try {
        & $FilePath @Arguments
        if ($LASTEXITCODE -ne 0) {
            throw ("Command failed with exit code {0}: {1} {2}" -f $LASTEXITCODE, $FilePath, ($Arguments -join " "))
        }
    }
    finally {
        Pop-Location
    }
}

if ($env:OS -ne "Windows_NT") {
    throw "The Chromium-Gost native build bootstrap must run on Windows."
}
if ($Workspace -match '\s') {
    throw "Use a workspace path without spaces. Upstream Chromium-Gost batch scripts use unquoted path variables."
}

$Workspace = [IO.Path]::GetFullPath($Workspace)
$driveRoot = [IO.Path]::GetPathRoot($Workspace)
$driveLetter = $driveRoot.Substring(0, 1)
$volume = Get-Volume -DriveLetter $driveLetter -ErrorAction Stop
if ($volume.FileSystem -ne "NTFS") {
    throw ("The source workspace must be on NTFS. Detected: {0}" -f $volume.FileSystem)
}
if ($volume.SizeRemaining -lt 120GB) {
    throw ("The workspace volume has {0:N1} GB free. Keep at least 120 GB free for Chromium source and build output." -f ($volume.SizeRemaining / 1GB))
}

$programFilesX86 = [Environment]::GetEnvironmentVariable("ProgramFiles(x86)")
$vswhere = Join-Path $programFilesX86 "Microsoft Visual Studio\Installer\vswhere.exe"
if (-not (Test-Path $vswhere)) {
    throw "Visual Studio Installer / vswhere was not found. Install Visual Studio 2026 with C++ desktop tools."
}
$vsInstall = & $vswhere -latest -products '*' -version '[18.0,19.0)' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vsInstall) {
    throw "Visual Studio 2026 (18.x) with MSVC x64/x86 tools was not found."
}

$sevenZipExe = Join-Path $programFilesX86 "7-Zip\7z.exe"
if (-not (Test-Path $sevenZipExe)) {
    $sevenZipExe = Join-Path $env:ProgramW6432 "7-Zip\7z.exe"
}
if (-not (Test-Path $sevenZipExe)) {
    throw "7-Zip was not found. The upstream release script expects 7-Zip under Program Files."
}
if (-not (Get-Command git.exe -ErrorAction SilentlyContinue)) {
    throw "Git for Windows is required."
}

New-Item -ItemType Directory -Force -Path $Workspace | Out-Null
$depotTools = Join-Path $Workspace "depot_tools"
$chromiumParent = Join-Path $Workspace "chromium"
$chromiumSrc = Join-Path $chromiumParent "src"
$gostRepo = Join-Path $Workspace "Chromium-Gost"

if (-not (Test-Path (Join-Path $depotTools "gclient.bat"))) {
    if (Test-Path $depotTools) { throw ("The depot_tools folder exists but gclient.bat is missing: {0}" -f $depotTools) }
    Invoke-NativeCommand -FilePath "git.exe" -Arguments @("clone", "--depth", "1", "https://chromium.googlesource.com/chromium/tools/depot_tools.git", $depotTools) -WorkingDirectory $Workspace
}

if (-not (Test-Path (Join-Path $gostRepo "build_windows\chromium-gost-prepare.bat"))) {
    if (Test-Path $gostRepo) { throw ("Chromium-Gost folder exists but is incomplete: {0}" -f $gostRepo) }
    Invoke-NativeCommand -FilePath "git.exe" -Arguments @("clone", "--depth", "1", "--branch", $ChromiumGostRef, "https://github.com/deemru/Chromium-Gost.git", $gostRepo) -WorkingDirectory $Workspace
}

$actualVersion = (Get-Content -Raw (Join-Path $gostRepo "VERSION")).Trim()
if ($actualVersion -ne $ChromiumGostRef) {
    throw ("Pinned source mismatch. Requested {0}; Chromium-Gost checkout reports {1}." -f $ChromiumGostRef, $actualVersion)
}
Invoke-NativeCommand -FilePath "git.exe" -Arguments @("submodule", "update", "--init", "--recursive", "--depth", "1") -WorkingDirectory $gostRepo

if (-not (Test-Path (Join-Path $chromiumSrc ".git"))) {
    if (-not $InitializeChromiumCheckout) {
        throw ("Chromium source is missing at {0}. Re-run with -InitializeChromiumCheckout to download the large source tree." -f $chromiumSrc)
    }
    New-Item -ItemType Directory -Force -Path $chromiumParent | Out-Null
    $env:PATH = "$depotTools;$env:PATH"
    $env:DEPOT_TOOLS_WIN_TOOLCHAIN = "0"
    Invoke-NativeCommand -FilePath (Join-Path $depotTools "fetch.bat") -Arguments @("chromium") -WorkingDirectory $chromiumParent
}
if (-not (Test-Path (Join-Path $chromiumSrc ".git"))) {
    throw ("Chromium checkout did not produce {0}." -f $chromiumSrc)
}

$privateEnv = Join-Path $gostRepo "build_windows\chromium-gost-env-private.bat"
$generatedMarker = "REM Generated by SkAi native-shell bootstrap"
if (Test-Path $privateEnv) {
    $existing = Get-Content -Raw $privateEnv
    if (-not $existing.Contains($generatedMarker)) {
        throw ("Refusing to overwrite an existing user-owned file: {0}" -f $privateEnv)
    }
}
$sevenZipDir = Split-Path -Parent $sevenZipExe
$quote = [char]34
$privateLines = @(
    $generatedMarker,
    ("set CHROMIUM_PATH={0}" -f $chromiumSrc),
    ("set DEPOT_TOOLS_PATH={0}" -f $depotTools),
    ("set SEVENZIP_PATH={0}{1}{0}" -f $quote, ($sevenZipDir + '\'))
)
$privateContent = $privateLines -join [Environment]::NewLine
[IO.File]::WriteAllText($privateEnv, $privateContent + [Environment]::NewLine, [Text.Encoding]::ASCII)

Write-Host "Sk/Ai native source environment prepared." -ForegroundColor Green
Write-Host ("Chromium-Gost: {0}" -f $ChromiumGostRef)
Write-Host ("Chromium source: {0}" -f $chromiumSrc)
Write-Host ("depot_tools: {0}" -f $depotTools)
Write-Host ("Visual Studio: {0}" -f $vsInstall)
